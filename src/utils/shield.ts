/**
 * Scans a given Thai script text for prohibited words.
 * Returns a list of issues found with their locations and details.
 */
export function scanScriptForProhibitedWords(text: string): ProhibitedWordIssue[] {
  if (!text) return [];

  const issues: ProhibitedWordIssue[] = [];

  for (const dictItem of PROHIBITED_WORDS_DICTIONARY) {
    // Escape regex characters just in case
    const escapedWord = dictItem.word.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
    const regex = new RegExp(escapedWord, "gi");
    const matches = text.match(regex);

    if (matches && matches.length > 0) {
      issues.push({
        word: dictItem.word,
        category: dictItem.category,
        reason: dictItem.reason,
        suggestion: dictItem.suggestion,
        count: matches.length
      });
    }
  }

  return issues;
}
